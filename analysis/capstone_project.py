"""# Task 9 — Correlation analysis


"""

cols = ['rating', 'returned', 'discount_pct', 'quantity']

corr = df_merged[cols].corr()

print("Hypothesis: Higher discounts reduce returns.")

for i in range(len(cols)):
    for j in range(i + 1, len(cols)):
        r = corr.iloc[i, j]
        band = ('negligible' if abs(r) < 0.2 else
                'weak' if abs(r) < 0.4 else
                'moderate' if abs(r) < 0.7 else 'strong')
        print(f"{cols[i]} vs {cols[j]}: r={r:.2f} → {band}")

print(f"\ndiscount_pct vs returned: r={corr.loc['discount_pct','returned']:.2f}")
print("Hypothesis: BUSTED")

