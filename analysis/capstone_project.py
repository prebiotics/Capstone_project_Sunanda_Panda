"""# Task 5 — Merge and reconcile against"""

# Merge the cleaned orders with products (on product_id) and customers (on customer_id).
df_merged = df1.merge(df2, on='product_id', how='left').merge(df, on='customer_id', how='left')
df_merged
print(df_merged.shape)

df_merged['order_value'] = (
    df_merged['quantity'] *
    df_merged['price'] *
    (1 - df_merged['discount_pct'] / 100)
)

