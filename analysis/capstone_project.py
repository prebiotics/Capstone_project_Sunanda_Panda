"""# Task 6 — IQR outlier detection on quantity"""

Q1 = df_merged['quantity'].quantile(0.25)
Q3 = df_merged['quantity'].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df_merged[(df_merged['quantity'] < lower_bound) | (df_merged['quantity'] > upper_bound)]
print("Number of outliers:", len(outliers))

"""# Task 7 — Hypothesis: does COD have a higher return rate?"""

print("Hypothesis: COD has the highest return rate compared with CARD and UPI.")

return_rates = df_merged.groupby('payment_method')['returned'].agg(['count', 'mean'])
return_rates['mean'] = return_rates['mean'] * 100

print("\nReturn rates:")
print(return_rates.round({'mean': 1}))
print("\nHypothesis: Confirmed")

"""# Task 8 — Multi-level segmentation"""

segment = (
    df_merged.groupby(['payment_method', 'city_tier'])['returned']
    .agg(['count', 'mean'])
)

segment['mean'] = segment['mean'] * 100

print("\nReturn rate by payment method and city tier (%):")
print(segment.round({'mean': 1}))

# Identify highest-risk segment

highest_risk = segment['mean'].idxmax()
highest_rate = segment['mean'].max()
